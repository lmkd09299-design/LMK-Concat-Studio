"""Copyright audit tests: no fake clearance, no need for a remote API."""
import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from core.media import MediaError, binary, execute, probe
from core.rights import audit_and_transform

SAMPLE = Path(__file__).resolve().parents[1] / 'fixtures' / 'sample.mp4'

class RightsReviewTests(unittest.TestCase):
    def test_report_only_does_not_claim_clearance(self):
        with tempfile.TemporaryDirectory() as d:
            report = audit_and_transform(str(SAMPLE), d)
            self.assertIsNone(report['output'])
            self.assertIn('CHƯA XÁC MINH', report['rights']['platform_clearance'])
            self.assertTrue(Path(report['checklist_csv']).exists())
            self.assertTrue(Path(d, 'report.json').exists())

    def test_mute_original_creates_silent_mp4(self):
        with tempfile.TemporaryDirectory() as d:
            report = audit_and_transform(str(SAMPLE), d, remove_original=True)
            output = Path(report['output'])
            self.assertTrue(output.exists())
            self.assertFalse(probe(output)['audio'])

    def test_replacement_requires_license_note(self):
        with tempfile.TemporaryDirectory() as d:
            music = Path(d) / 'licensed.wav'; music.touch()
            with self.assertRaises(MediaError):
                audit_and_transform(str(SAMPLE), d, replacement_audio=str(music))

    def test_replacement_track_produces_mp4(self):
        with tempfile.TemporaryDirectory() as d:
            music = Path(d) / 'licensed.wav'
            execute([binary('ffmpeg'), '-hide_banner', '-loglevel', 'error', '-y',
                     '-f', 'lavfi', '-i', 'sine=frequency=440:duration=0.6', str(music)])
            report = audit_and_transform(str(SAMPLE), d, replacement_audio=str(music),
                                         license_note='Test sine generated by FFmpeg')
            self.assertTrue(probe(report['output'])['audio'])
            self.assertTrue(report['rights']['original_audio_removed'])

if __name__ == '__main__': unittest.main()
